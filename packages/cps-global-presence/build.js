/* build.js — assemble the presence clients from bundles.json.
 *
 * Run through ./build.sh, the entry point CI and deploy.local.sh call.
 *
 * The sources are hand-written scripts, not modules: nothing transpiles down to
 * Classic's document mode 5, so each one declares a CCP* namespace with `var`,
 * check-syntax.js proves the floor, and this concatenates them in manifest order.
 * The same manifest drives test-harness.js's bundle(), so tests load exactly
 * what ships.
 *
 * Outputs, all named for where they are published (CI copies them by name):
 *   dist/cms-augmentation/client-{classic,modern}-unstable.js  the real clients,
 *     injected by our proxied CMS
 *   dist/cms-augmentation/client-{classic,modern}.js           permanent placeholders:
 *     the URLs the CMS maintainers link to, inert until we drop "-unstable" from
 *     the injected src (a one-line nginx change, no rebuild)
 *   dist/esm/index.js                                          the shared modules
 *     as ESM, for the web components
 *   types/index.d.ts                                           wire shapes + tsc's
 *     surface from the JSDoc
 */
var fs = require("fs");
var path = require("path");
var execFileSync = require("child_process").execFileSync;

var DIR = __dirname;
var manifest = JSON.parse(fs.readFileSync(path.join(DIR, "bundles.json"), "utf8"));
// How every JWT starts ('{"typ":"JWT"' in base64), so a token pasted into a
// source is caught before it ships. Computed, so the check itself carries nothing
// a secret scanner would flag.
var CREDENTIAL = Buffer.from('{"typ":"JWT"').toString("base64");

var files = function (groupNames) {
  return [].concat.apply([], (groupNames || []).map(function (g) {
    return manifest.groups[g].files;
  }));
};

var read = function (rel) {
  return fs.readFileSync(path.join(DIR, rel), "utf8");
};

var indent = function (src) {
  var lines = src.split("\n");
  if (lines[lines.length - 1] === "") {
    lines.pop();
  }
  return lines.map(function (l) { return "  " + l; }).join("\n") + "\n";
};

var checkFloor = function (level, paths) {
  if (!paths.length) {
    return;
  }
  execFileSync("node", [path.join(DIR, "check-syntax.js"), level].concat(paths), { stdio: "inherit" });
};

var write = function (rel, text) {
  if (text.indexOf(CREDENTIAL) !== -1) {
    throw new Error("a credential leaked into " + rel);
  }
  var abs = path.join(DIR, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, text);
  console.log("built " + rel + " (" + Buffer.byteLength(text) + " bytes)");
};

var lines = function (arr) {
  return arr.join("\n") + "\n";
};

var concatIife = function (groupNames) {
  return files(groupNames).map(function (f) {
    return "\n  /* ================= " + f + " ================= */\n" + indent(read(f));
  }).join("");
};

var raw = function (groupNames) {
  return files(groupNames).map(read).join("");
};

// ---- gates: source floors, then types ----------------------------------------
// A floor violation should fail here, naming file and line, not show up as a
// blank page in an IE-mode tab.
console.log("--- floor checks ---");
["es3", "es5"].forEach(function (level) {
  var names = Object.keys(manifest.groups).filter(function (g) {
    return manifest.groups[g].floor === level;
  });
  checkFloor(level, files(names).map(function (f) { return path.join(DIR, f); }));
});
Object.keys(manifest.placeholders).forEach(function (out) {
  var p = manifest.placeholders[out];
  checkFloor(p.floor, [path.join(DIR, p.from)]);
});

// tsc type-checks the shared JSDoc and generates types/common.d.ts. It knows our
// functions but not the server's wire shapes, so the published file is the
// hand-written wire contract followed by the generated surface.
var TSC = path.join(DIR, "../../node_modules/.bin/tsc");
if (fs.existsSync(TSC)) {
  console.log("--- types ---");
  execFileSync(TSC, ["-p", DIR], { stdio: "inherit" });
  fs.writeFileSync(path.join(DIR, "types/index.d.ts"), lines([
    "/* types/index.d.ts — GENERATED by build.sh. DO NOT EDIT.",
    " *",
    " * The published surface of core/ and legacy/. Two halves:",
    " *   1. core/wire.d.ts      the wire shapes (hand-written:",
    " *                          they describe the SERVER's contract, so there is",
    " *                          nothing in our code to infer them from)",
    " *   2. types/common.d.ts   our functions, generated by tsc from the JSDoc",
    " *                          in core/ and legacy/, so they cannot drift",
    " */",
    ""
  ]) + read("core/wire.d.ts") + "\n" + read("types/common.d.ts"));
  console.log("ok   tsc  type-checked, types/index.d.ts regenerated");
} else {
  console.log("skip tsc  (compiler not found — types not re-checked)");
}

console.log("--- output ---");

// ---- Modern/DCF: one strict IIFE (document mode 11) -----------------------------
var modern = manifest.bundles.modern;
write(modern.out, lines([
  "/* " + path.basename(modern.out) + " — GENERATED by build.sh. DO NOT EDIT.",
  " *",
  " * Presence client for CMS Modern (/viewer/) and DCF (/dcf/), which run in Edge",
  " * IE mode at document mode 11. JSONP transport — no vendor code, no Promise",
  " * polyfill, nothing patched onto the host page.",
  " *",
  " * Assembled from:",
  " *   core/         shared with the web components and the Classic client",
  " *   legacy/       shared with the Classic client — mode 5 floor",
  " *   apps/modern/  this app only",
  " *",
  " * Edit those sources and re-run build.sh.",
  " */",
  "(function () {",
  '  "use strict";',
  "",
  "  // Each module declares its own CCP* namespace. Concatenation rather",
  "  // than modules: the injected script has no loader, and document mode 5 has no",
  "  // module system. Order is bundles.json's."
]) + concatIife(modern.iife) + "})();\n");

// ---- ESM, for the web components --------------------------------------------
// Only what they import is exported: these files assign module-scope variables,
// so nothing can be tree-shaken out of their bundle.
var esm = manifest.bundles.esm;
write(esm.out, lines([
  "/* dist/esm/index.js — GENERATED by build.sh. DO NOT EDIT.",
  " *",
  " * The shared presence modules as an ES module, for the web components. The same",
  " * sources ship to CMS Classic and CMS Modern as concatenated IIFEs; this is the",
  " * bundler-facing shape of them, so the three clients cannot diverge.",
  " */"
]) + files(esm.esm).map(function (f) {
  return "\n/* ================= " + f + " ================= */\n" + read(f);
}).join("") + "\nexport { " + esm.exports.join(", ") + " };\n");

// ---- Classic: kill switch, presence IIFE, auth IIFE (document mode 5) -----------
// The switch sits outside both IIFEs because both read it. Two IIFEs so a failure
// in one concern cannot reach the other. No "use strict": this has always run in
// sloppy mode inside someone else's application.
var classic = manifest.bundles.classic;
write(classic.out, lines([
  "/* " + path.basename(classic.out) + " — GENERATED by cps-global-presence/build.sh. DO NOT EDIT.",
  " *",
  " * Injected into the persistent CMS Classic frameset shell (uaglCMS.aspx <head>),",
  " * which loads once per session and persists THROUGH login. Two independent",
  " * concerns, each its own IIFE so a failure in one cannot affect the other:",
  " *   1. section presence",
  " *   2. the login -> auth iframe hand-off",
  " *",
  " * Document mode 5 (old JScript): no const/let/arrow, no trailing commas, no",
  " * Array.forEach/indexOf, no String.trim, no JSON, no querySelector, no",
  " * addEventListener. build.sh proves it with check-syntax.js es3.",
  " *",
  " * Assembled from packages/cps-global-presence/:",
  " *   core/, legacy/  shared with the Modern/DCF client",
  " *   apps/classic/   this app only",
  " *",
  " * CMS_WATCHDOG_ENABLED (apps/classic/kill-switch.js) is emitted at the top, outside",
  " * both IIFEs: set it false and redeploy to stop both concerns dead.",
  " *",
  " * Edit those sources and re-run build.sh.",
  " */",
  ""
]) + raw(classic.before) + "(function () {\n" + concatIife(classic.iife) + "})();\n\n" + raw(classic.after));

// ---- the outputs themselves pass their floor ---------------------------------
checkFloor(modern.floor, [path.join(DIR, modern.out)]);
checkFloor(classic.floor, [path.join(DIR, classic.out)]);

// ---- placeholders, copied as-is ------------------------------------------------
Object.keys(manifest.placeholders).forEach(function (out) {
  write(out, read(manifest.placeholders[out].from));
});
