#!/usr/bin/env bash
#
# build.sh — assemble the injected presence client.
#
#   ./build.sh           JSONP client (what ships): common/ + modern/, concatenated
#                        into one IIFE. No vendor, no Promise polyfill, nothing
#                        patched onto the host page.
#
#   ./build.sh signalr   the reference SignalR client: vendor/es6-promise +
#                        vendor/signalr 3.1 + cms-presence-client.signalr.src.js.
#                        See that file's header for why it is not the shipping one.
#
# Both emit ../cms-presence-client.js, so nginx and the deploy script never change.
#
# CODE SHARING
#   common/  runs in BOTH legacy clients, so it is held to the DOCUMENT MODE 5
#            floor — Classic's engine. Proven by check-syntax.js es3: ES3 syntax
#            plus a denylist of the ES5 runtime Classic does not have. There is no
#            tool that transpiles down to mode 5 (TypeScript removed its ES3
#            target, esbuild's floor is a partial es5, and Babel cannot conjure a
#            missing JSON or Array.prototype.forEach), so the floor is written by
#            hand and enforced mechanically.
#   modern/  Modern/DCF only (document mode 11), so ES5 is its floor.
#
# The order below matters: common/ declares CCP.* which modern/ consumes, and
# modern/main.js runs on load, so it goes last.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$DIR/../cms-presence-client.js"

VARIANT="${1:-jsonp}"

if [ "$VARIANT" = "signalr" ]; then
  SRC="$DIR/cms-presence-client.signalr.src.js"
  [ -f "$SRC" ] || { echo "Missing $SRC" >&2; exit 1; }
  {
    echo "/* cms-presence-client.js — GENERATED by cms-presence-client/build.sh signalr."
    echo " * DO NOT EDIT. Reference SignalR variant; see cms-presence-client.signalr.src.js."
    echo " */"
    echo
    echo "/* ---- 1. es6-promise 4.2.8 (MIT) ---- */"
    cat "$DIR/vendor/es6-promise-4.2.8.auto.min.js"
    echo
    echo "/* ---- 2. @microsoft/signalr 3.1.31 (Apache-2.0) ---- */"
    cat "$DIR/vendor/signalr-3.1.31.min.js"
    echo
    echo "/* ---- 3. presence glue ---- */"
    cat "$SRC"
  } > "$OUT"
  echo "built $OUT (signalr variant, $(wc -c < "$OUT" | tr -d ' ') bytes)"
  exit 0
fi

COMMON="$DIR/common/presence-sections.js $DIR/common/presence-origin.js $DIR/common/presence-roster.js $DIR/common/presence-jsonp.js"
MODERN="$DIR/modern/context.js $DIR/modern/bar.js $DIR/modern/transport-jsonp.js $DIR/modern/transport-signalr.js $DIR/modern/main.js"
PLUGIN="$DIR/signalr/plugin.js"

# Gate BEFORE building: a floor violation should fail here, naming the file and
# line, rather than surfacing as a blank page in an IE-mode tab.
echo "--- floor checks ---"
node "$DIR/check-syntax.js" es3 $COMMON
node "$DIR/check-syntax.js" es5 $MODERN $PLUGIN

# common/ is plain JS, but tsc type-checks it from its JSDoc and REGENERATES
# types/common.d.ts — the surface global-components would import. Nothing is
# emitted into the shipping path; this only proves the shared code is internally
# consistent and keeps its published types from drifting. Skipped if the compiler
# is not present (a bare checkout of the proxy folder alone).
TSC="$DIR/../../../../../node_modules/.bin/tsc"
if [ -x "$TSC" ]; then
  echo "--- types ---"
  "$TSC" -p "$DIR"
  # tsc's output describes OUR functions but only REFERENCES the API's wire shapes
  # (CCPSection, CCPNotification, CCPPerson) — it defines none of them, so it is not
  # usable on its own. Publish one self-contained file instead: the hand-written wire
  # contract followed by the generated surface.
  {
    echo "/* types/index.d.ts — GENERATED by build.sh. DO NOT EDIT."
    echo " *"
    echo " * The published surface of common/. Two halves:"
    echo " *   1. common/types.d.ts   the presence API's wire shapes (hand-written:"
    echo " *                          they describe the SERVER's contract, so there is"
    echo " *                          nothing in our code to infer them from)"
    echo " *   2. types/common.d.ts   our functions, generated by tsc from the JSDoc"
    echo " *                          in common/*.js, so they cannot drift"
    echo " */"
    echo
    cat "$DIR/common/types.d.ts"
    echo
    cat "$DIR/types/common.d.ts"
  } > "$DIR/types/index.d.ts"
  echo "ok   tsc  common/*.js type-checked, types/index.d.ts regenerated"
else
  echo "skip tsc  (compiler not found — types not re-checked)"
fi

{
  echo "/* cms-presence-client.js — GENERATED by cms-presence-client/build.sh. DO NOT EDIT."
  echo " *"
  echo " * Presence client for CMS Modern (/viewer/) and DCF (/dcf/), which run in Edge"
  echo " * IE mode at document mode 11. JSONP transport — no vendor code, no Promise"
  echo " * polyfill, nothing patched onto the host page."
  echo " *"
  echo " * Assembled from:"
  echo " *   common/  shared with the Classic client — held to the document mode 5 floor"
  echo " *   modern/  Modern/DCF only"
  echo " *"
  echo " * Edit those sources and re-run build.sh."
  echo " */"
  echo "(function () {"
  echo '  "use strict";'
  echo
  echo "  // Each common module declares its own CCP* namespace. Concatenation rather"
  echo "  // than modules: the injected script has no loader, and document mode 5 has no"
  echo "  // module system. Order matters — presence-sections defines what the others use."
  for f in $COMMON $MODERN; do
    echo
    echo "  /* ================= $(basename "$(dirname "$f")")/$(basename "$f") ================= */"
    sed 's/^/  /' "$f"
  done
  echo "})();"
} > "$OUT"

echo "--- output ---"
node "$DIR/check-syntax.js" es5 "$OUT"
grep -q "eyJ0eXAiOiJKV1Qi" "$OUT" && { echo "ERROR: a credential leaked into the bundle" >&2; exit 1; }
echo "built $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes), no credential"

# ---- the lazily-loaded SignalR transport --------------------------------------
#
# A SECOND artefact, deployed alongside the first and fetched only when someone
# calls __ccPresence.setTransport("signalr"). It carries the vendor code — the
# library plus a Promise polyfill this engine has no other source for — which is
# ~4x the size of the entire shipping client and has no business on every page
# load for a transport we are still evaluating. modern/transport-signalr.js is the
# loader; this is what it loads.
SIGNALR_OUT="$DIR/../cms-presence-signalr.js"
{
  echo "/* cms-presence-signalr.js — GENERATED by cms-presence-client/build.sh. DO NOT EDIT."
  echo " *"
  echo " * The optional SignalR transport for cms-presence-client.js, loaded on demand"
  echo " * from the same directory. Publishes ONE global, window.CCPSignalRFactory."
  echo " *"
  echo " * Edit signalr/plugin.js and re-run build.sh."
  echo " */"
  echo
  echo "/* ---- 1. es6-promise 4.2.8 (MIT) ---- */"
  cat "$DIR/vendor/es6-promise-4.2.8.auto.min.js"
  echo
  echo "/* ---- 2. @microsoft/signalr 3.1.31 (Apache-2.0) ---- */"
  cat "$DIR/vendor/signalr-3.1.31.min.js"
  echo
  echo "/* ---- 3. transport ---- */"
  cat "$PLUGIN"
} > "$SIGNALR_OUT"
echo "built $SIGNALR_OUT ($(wc -c < "$SIGNALR_OUT" | tr -d ' ') bytes, on-demand)"
